# Names people actually type, mapped to codes. Demonyms that are also language names ("korean", "french") are
# deliberately absent: those are language hints, not country hints.
_ALIASES = {
    "usa": "US",
    "us": "US",
    "america": "US",
    "united states": "US",
    "uk": "GB",
    "britain": "GB",
    "england": "GB",
    "united kingdom": "GB",
    "korea": "KR",
    "south korea": "KR",
    "uae": "AE",
    "emirates": "AE",
    "turkey": "TR",
    "czech republic": "CZ",
    "holland": "NL",
}
_NAME_TO_CODE = {name.casefold(): code for code, name in COUNTRIES.items() if code not in ("XW", "XE")}
_NAME_TO_CODE.update(_ALIASES)


def country_name(code: str | None) -> str | None:
    return COUNTRIES.get(code.upper(), code.upper()) if code else None


def find_country(text: str) -> tuple[str | None, str]:
    """Pull one country mention out of free text. Returns (code, text without the mention)."""
    lowered = f" {text.casefold()} "
    for name in sorted(_NAME_TO_CODE, key=len, reverse=True):
        needle = f" {name} "
        if needle in lowered:
            return _NAME_TO_CODE[name], " ".join(lowered.replace(needle, " ", 1).split())
    return None, text
